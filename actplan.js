/* R²-SAFE: แผนดำเนินการรายมาตรการ (ช่วงเวลา · กิจกรรม · ผู้รับผิดชอบ · ผลที่ได้)
   สร้างจากข้อมูลของมาตรการในคลัง (กิจกรรมหลัก ผลผลิต ตัวชี้วัด เงื่อนไขก่อนดำเนินการ ทรัพยากร ผู้รับผิดชอบ กลุ่มเป้าหมาย ช่วง ระดับทรัพยากร)
   ร่วมกับกรอบขั้นตอนตามช่วงของมาตรการ (ป้องกัน เตรียมพร้อม ตอบสนอง ฟื้นฟู) ไม่ใช่แผนที่ผู้เชี่ยวชาญเขียนรายมาตรการ
   ช่วงเวลาเป็นสัปดาห์นับจากวันเริ่มดำเนินการ โรงเรียนปรับให้ตรงปฏิทินของตนเอง
   ไฟล์นี้ไม่มี DOM และไม่ส่งข้อมูลไปที่ใด */
(function (root) {
  'use strict';
  const isNode = typeof module !== 'undefined' && module.exports;

  // ระยะรวมของแผน (สัปดาห์) ตามระดับทรัพยากรของมาตรการ: ใช้ทรัพยากรมากต้องใช้เวลาเตรียมและขออนุมัติมากขึ้น
  const TOTAL = { 1: 4, 2: 8, 3: 12 };
  const RESNOTE = {
    1: 'ใช้ทรัพยากรที่มีอยู่ในโรงเรียน ไม่ต้องขอเพิ่ม',
    2: 'ต้องจัดสรรเวลาและงบประมาณเพิ่มเล็กน้อย เสนอผู้อำนวยการอนุมัติ',
    3: 'ใช้ทรัพยากรมาก เสนอผู้อำนวยการและขอรับการสนับสนุนจากต้นสังกัดหรือภาคีที่เกี่ยวข้อง',
  };
  const LEAD = { 'ป้องกัน': 'ดำเนินกิจกรรมหลัก', 'เตรียมพร้อม': 'จัดกิจกรรมเตรียมความพร้อม', 'ตอบสนอง': 'กำหนดและเขียนขั้นตอนการตอบสนอง', 'ฟื้นฟู': 'ดำเนินการดูแลและฟื้นฟู' };
  const TRY = {
    'ป้องกัน': ['ทดลองใช้กับกลุ่มเล็ก เช่น 1 ห้องเรียนหรือ 1 กิจกรรม แล้วรับฟังข้อสังเกตจากผู้เกี่ยวข้อง ปรับปรุงก่อนใช้ทั่วโรงเรียน', 'ข้อสังเกตจากการทดลองใช้และฉบับปรับปรุง', 'ทดลองใช้และปรับปรุง'],
    'เตรียมพร้อม': ['ซ้อมหรืออบรมจริงตามกำหนด บันทึกเวลา ปัญหา และข้อสังเกตของผู้เข้าร่วม', 'บันทึกผลการซ้อมหรืออบรมและข้อเสนอปรับปรุง', 'ซ้อมหรืออบรมจริงและบันทึกผล'],
    'ตอบสนอง': ['ซ้อมบนโต๊ะตามขั้นตอนที่เขียน ตรวจว่าทุกคนรู้บทบาทและช่องทางสื่อสาร แล้วแก้ขั้นตอนที่สับสน', 'บันทึกผลการซ้อมบนโต๊ะและขั้นตอนที่แก้ไข', 'ซ้อมบนโต๊ะและแก้ขั้นตอน'],
    'ฟื้นฟู': ['ทดลองใช้กับกรณีจำลองโดยไม่ใช้ข้อมูลจริงของนักเรียน ตรวจสิทธิ์การเข้าถึงและการรักษาความลับ', 'ผลตรวจสิทธิ์การเข้าถึงและการรักษาความลับจากกรณีจำลอง', 'ทดลองกับกรณีจำลอง'],
  };
  const wk = (a, b) => 'สัปดาห์ที่ ' + (a === b ? a : a + '–' + b);
  const noPre = (p) => !p || /^ไม่มี/.test(String(p).trim());

  // m = มาตรการ, ctx = { review: 'ทุกเดือน', start: 'ภายใน 1 สัปดาห์' }
  // คืน [{ when, what, brief, who, out }] 6 ขั้น เรียงตามเวลา
  function steps(m, ctx) {
    const c = ctx || {}, T = TOTAL[m.res] || TOTAL[2], phase = LEAD[m.phase] ? m.phase : 'ป้องกัน', owner = m.owner || 'ผู้รับผิดชอบ', target = m.target || 'ผู้เกี่ยวข้อง';
    const a2 = Math.max(1, Math.ceil(T * 0.25)), a3 = Math.max(a2, Math.ceil(T * 0.5)), a4 = Math.max(a3, Math.ceil(T * 0.75)), ids = String(m.prereq || '').match(/SB-\d+/g) || [];
    const t = TRY[phase], pre = noPre(m.prereq);
    return [
      { when: wk(1, 1), what: 'ประชุมชี้แจงและมอบหมายงาน: แต่งตั้ง' + owner + 'เป็นผู้รับผิดชอบ ชี้แจงเป้าหมายและตัวชี้วัดแก่' + target + (pre ? ' (เริ่มได้ทันที ไม่มีเงื่อนไขก่อนดำเนินการ)' : ' และตรวจเงื่อนไขก่อนดำเนินการ: ' + m.prereq),
        brief: 'ประชุมมอบหมายงาน' + (pre ? '' : ' ตรวจเงื่อนไข ' + ids.join(', ')), who: 'ผู้อำนวยการ · ' + owner, out: 'บันทึกการมอบหมายงาน' + (pre ? '' : ' และผลตรวจเงื่อนไข') },
      { when: wk(1, a2), what: 'เตรียมทรัพยากร: ' + m.resources + ' (' + RESNOTE[m.res || 2] + ')',
        brief: 'เตรียมทรัพยากร', who: owner, out: 'ทรัพยากรที่พร้อมใช้' + ((m.res || 2) > 1 ? ' และงบที่อนุมัติ' : '') },
      { when: wk(a2 === 1 ? 2 : a2, a3 < 2 ? 2 : a3), what: LEAD[phase] + ': ' + m.desc,
        brief: LEAD[phase] + 'ตามวัตถุประสงค์', who: owner, out: 'ร่างของ' + m.output },
      { when: wk(Math.max(a3, 2), Math.max(a4, a3, 2)), what: t[0], brief: t[2], who: owner + ' · ' + target, out: t[1] },
      { when: wk(a4 < T ? a4 : T, T), what: 'ประกาศใช้และสื่อสารให้' + target + ' ผู้ปกครอง และบุคลากรที่เกี่ยวข้องรับทราบ แล้วเก็บหลักฐานและสิ่งที่ส่งมอบ: ' + m.output, brief: 'ประกาศใช้ เก็บหลักฐาน: ' + m.output, who: 'ผู้อำนวยการ · ' + owner, out: m.output },
      { when: 'หลังสิ้นสุด และ' + (c.review ? c.review : 'ตามรอบทบทวน'), what: 'วัดผลด้วยตัวชี้วัด "' + m.kpi + '" เสนอผลต่อผู้อำนวยการ และทบทวนตามรอบ' + (c.review ? ' (' + c.review + ')' : '') + ' แล้วปรับแผน', brief: 'วัดผลและทบทวน' + (c.review ? ' (' + c.review + ')' : ''), who: owner + ' · ผู้อำนวยการ', out: 'รายงานผลและข้อเสนอปรับแผน' },
    ];
  }

  const api = { steps, TOTAL, RESNOTE };
  if (isNode) module.exports = api; else root.RS_ACTPLAN = api;
})(typeof window !== 'undefined' ? window : this);
